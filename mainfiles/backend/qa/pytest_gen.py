"""Generate a CI-ready pytest file from a QA cassette.

The generated file is self-contained except for the repo location:
it resolves the Sangam root from ``SANGAM_REPO_ROOT`` (set by CI
when the file lives outside ``tests/``) or, by default, from its own
path assuming it was copied into ``tests/`` (``parents[1]`` — the
same pattern the existing deep-pipeline tests use). Each case
becomes one test that replays that case through a fresh TestClient
with a freshly registered user (auth headers are supplied at replay
time, never recorded). A skipped case becomes a ``pytest.skip`` test,
not a silent omission — the report's skipped bucket stays visible.
"""
from __future__ import annotations

from pathlib import Path

_TEMPLATE = '''"""Generated by backend.qa.pytest_gen — DO NOT EDIT BY HAND.

Replays a recorded QA cassette (one test per case) against a fresh
TestClient. Regenerate after re-recording; do not hand-edit cases.
"""
from __future__ import annotations

import asyncio
import importlib
import os
import sys
from pathlib import Path

os.environ["TEST_MODE"] = "1"

_ROOT = Path(os.environ.get("SANGAM_REPO_ROOT", Path(__file__).resolve().parents[1]))
if str(_ROOT / "mainfiles") not in sys.path:
    sys.path.insert(0, str(_ROOT / "mainfiles"))

import pytest  # noqa: E402

from backend.config import settings  # noqa: E402
from backend.database import Base, get_engine, reset_engine_for_testing  # noqa: E402
from backend.main import create_app  # noqa: E402
from backend.qa.recorder import load_cassette  # noqa: E402
from backend.qa.replay import replay_case  # noqa: E402
from fastapi.testclient import TestClient  # noqa: E402

CASSETTE = Path(__file__).with_suffix(".json")
CASES = load_cassette(CASSETTE)


@pytest.fixture
def client(tmp_path, monkeypatch):
    os.environ["CHROMA_DB_PATH"] = str(tmp_path / "chroma")
    import backend.rag as rag_mod
    importlib.reload(rag_mod)
    rag_mod._client = None
    rag_mod._collection = None
    from backend import memory as memory_mod
    memory_mod.reset_memory_for_testing()
    monkeypatch.setattr(settings, "DATABASE_URL",
                        f"sqlite+aiosqlite:///{tmp_path}/qa-replay.db")
    reset_engine_for_testing()

    async def _create_all():
        engine = get_engine()
        async with engine.begin() as conn:
            await conn.run_sync(Base.metadata.create_all)

    asyncio.run(_create_all())
    return TestClient(create_app())


@pytest.fixture
def auth_headers(client):
    creds = {"username": "qa_replay_user", "password": "StrongPass123!"}
    r = client.post("/api/auth/register", json=creds)
    data = r.json() if r.status_code == 201 else client.post(
        "/api/auth/login", json=creds).json()
    return {"Authorization": f"Bearer {data['access_token']}",
            "X-CSRF-Token": data["csrf_token"]}


@pytest.mark.parametrize("case", CASES, ids=lambda c: f"{c['method']} {c['path']}")
def test_replayed_case(client, auth_headers, case):
    if case.get("skip"):
        pytest.skip("case skipped at record time")
    result = replay_case(client, case, extra_headers=auth_headers)
    assert result["passed"], result.get("diff", "")
'''


def generate_pytest_file(cassette_path: Path | str, out_path: Path | str) -> Path:
    """Write the pytest file next to a cassette JSON of the same stem.

    Returns the written path. The generated file loads
    ``<stem>.json`` sitting beside it, so callers should copy the
    cassette JSON next to the generated file (or generate directly
    into the cassette's directory).
    """
    from .recorder import load_cassette
    cases = load_cassette(cassette_path)
    if not cases:
        raise ValueError("cannot generate tests from an empty cassette")
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(_TEMPLATE, encoding="utf-8")
    return out
